/// Quick Look thumbnail (real page / frame preview for images, PDFs, videos, documents, folders ...)
fn quicklook(path: &str, px: f64) -> Option<Retained<NSImage>> {
    use block2::RcBlock;
    use objc2::runtime::AnyClass;
    let gen_cls = AnyClass::get(c"QLThumbnailGenerator")?;
    let req_cls = AnyClass::get(c"QLThumbnailGenerationRequest")?;
    let url = NSURL::fileURLWithPath(&NSString::from_str(path));
    let (tx, rx) = channel::<Option<Retained<NSImage>>>();
    let tx = Mutex::new(Some(tx));
    unsafe {
        let req: Option<Retained<AnyObject>> = msg_send![msg_send![req_cls, alloc],
            initWithFileAtURL: &*url, size: NSSize::new(px, px), scale: 2.0f64, representationTypes: usize::MAX];
        let req = req?;
        let gen: Option<Retained<AnyObject>> = msg_send![gen_cls, sharedGenerator];
        let gen = gen?;
        let blk = RcBlock::new(move |rep: *mut AnyObject, _err: *mut AnyObject| {
            let img: Option<Retained<NSImage>> = if rep.is_null() { None } else { msg_send![&*rep, NSImage] };
            if let Some(t) = tx.lock().unwrap().take() { let _ = t.send(img); }
        });
        let _: () = msg_send![&*gen, generateBestRepresentationForRequest: &*req, completionHandler: &*blk];
    }
    rx.recv_timeout(Duration::from_secs(4)).ok().flatten()
}

/// File preview as a PNG data URL: Quick Look thumbnail, otherwise the Finder icon
pub fn icon_data_url(path: &str, px: i32) -> Option<String> {
    icon_png(path, px as f64).map(|p| png_data_url(&p))
}

fn icon_png(path: &str, px: f64) -> Option<Vec<u8>> {
    if path.is_empty() || !std::path::Path::new(path).exists() { return None; }
    if let Some(img) = quicklook(path, px) {
        if let Some(png) = nsimage_png(&img, px * 2.0) { return Some(png); }
    }
    let img = NSWorkspace::sharedWorkspace().iconForFile(&NSString::from_str(path));
    nsimage_png(&img, px * 2.0)
}

/* ---------- drag out (Finder, Mail, Messages, browsers ...) ---------- */
pub fn drag_files(win: &tauri::WebviewWindow, files: Vec<String>, done: impl FnOnce() + Send + 'static) {
    let image = files.first().and_then(|f| icon_png(f, 64.0)).unwrap_or_else(|| include_bytes!("../../icons/tray.png").to_vec());
    let w = win.clone();
    let done = Mutex::new(Some(done));
    let _ = win.run_on_main_thread(move || {
        crate::winutil::DRAGGING.store(true, std::sync::atomic::Ordering::Relaxed);
        let item = drag::DragItem::Files(files.iter().map(std::path::PathBuf::from).collect());
        let res = drag::start_drag(&w, item, drag::Image::Raw(image), move |_r, _p| {
            crate::winutil::DRAGGING.store(false, std::sync::atomic::Ordering::Relaxed);
            if let Some(d) = done.lock().unwrap().take() { d(); }
        }, drag::Options::default());
        if res.is_err() { crate::winutil::DRAGGING.store(false, std::sync::atomic::Ordering::Relaxed); }
    });
}

/* ---------- clipboard ---------- */
pub enum ClipContent { Files(Vec<String>), Png(Vec<u8>), Text(String), Empty }

fn pb() -> Retained<NSPasteboard> { NSPasteboard::generalPasteboard() }

fn types() -> Vec<String> {
    pb().types().map(|t| t.to_vec().iter().map(|s| s.to_string()).collect()).unwrap_or_default()
}

/// Password managers and other apps mark secrets with the nspasteboard.org conventions: keep those out of the history
pub fn clipboard_is_private() -> bool {
    const PRIVATE: [&str; 7] = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type",
    ];
    types().iter().any(|t| PRIVATE.contains(&t.as_str()))
}

pub fn clipboard_seq() -> u32 { pb().changeCount() as u32 }

pub fn clipboard_set_text(text: &str) -> bool {
    let text = text.to_string();
    on_main(move |_| {
        let p = pb();
        p.clearContents();
        unsafe { p.setString_forType(&NSString::from_str(&text), objc2_app_kit::NSPasteboardTypeString) }
    }).unwrap_or(false)
}

/// Put files on the clipboard (paste in Finder with ⌘V, attach in Mail ...)
pub fn clipboard_set_files(paths: &[String]) -> Result<(), ()> {
    let paths = paths.to_vec();
    let ok = on_main(move |_| {
        let urls: Vec<Retained<NSURL>> = paths.iter().map(|p| NSURL::fileURLWithPath(&NSString::from_str(p))).collect();
        let arr = NSArray::from_retained_slice(&urls);
        let p = pb();
        p.clearContents();
        unsafe { msg_send![&*p, writeObjects: &*arr] }
    }).unwrap_or(false);
    if ok { Ok(()) } else { Err(()) }
}

pub fn clipboard_read() -> ClipContent {
    let p = pb();
    let ts = types();
    let has = |t: &str| ts.iter().any(|x| x == t);
    // 1. files copied in Finder
    if has("public.file-url") {
        let mut files = Vec::new();
        if let Some(items) = p.pasteboardItems() {
            for it in items.to_vec() {
                if let Some(s) = it.stringForType(&NSString::from_str("public.file-url")) {
                    if let Some(u) = NSURL::URLWithString(&s) {
                        if let Some(path) = u.path() { files.push(path.to_string()); }
                    }
                }
            }
        }
        if !files.is_empty() { return ClipContent::Files(files); }
    }
    // 2. image (screenshot with ⌃⇧⌘4, "Copy Image" in Safari ...)
    if has("public.png") {
        if let Some(d) = p.dataForType(&NSString::from_str("public.png")) { return ClipContent::Png(d.to_vec()); }
    }
    if has("public.tiff") {
        if let Some(d) = p.dataForType(&NSString::from_str("public.tiff")) {
            if let Some(png) = tiff_to_png(&d) { return ClipContent::Png(png); }
        }
    }
    // 3. text
    if let Some(s) = unsafe { p.stringForType(objc2_app_kit::NSPasteboardTypeString) } {
        let s = s.to_string();
        if !s.trim().is_empty() { return ClipContent::Text(s); }
    }
    ClipContent::Empty
}

fn tiff_to_png(d: &NSData) -> Option<Vec<u8>> {
    let rep = NSBitmapImageRep::imageRepWithData(d)?;
    let out = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &NSDictionary::new()) }?;
    Some(out.to_vec())
}

/* ---------- folder picker ---------- */
pub fn pick_folder(title: &str) -> Option<String> {
    let title = title.to_string();
    on_main(move |mtm| {
        crate::macos::activate_self();
        let panel = objc2_app_kit::NSOpenPanel::openPanel(mtm);
        panel.setCanChooseDirectories(true);
        panel.setCanChooseFiles(false);
        panel.setAllowsMultipleSelection(false);
        panel.setCanCreateDirectories(true);
        panel.setMessage(Some(&NSString::from_str(&title)));
        if panel.runModal() != 1 { return None; }   // NSModalResponseOK
        panel.URL().and_then(|u| u.path()).map(|p| p.to_string())
    }).flatten()
}

/// Physical RAM (bytes)
pub fn total_ram() -> u64 {
    let mut v: u64 = 0;
    let mut len = std::mem::size_of::<u64>();
    let r = unsafe { libc::sysctlbyname(c"hw.memsize".as_ptr(), &mut v as *mut u64 as *mut _, &mut len, std::ptr::null_mut(), 0) };
    if r == 0 && v > 0 { v } else { 8 << 30 }
}

